"""Stage E2 harness (GAP-HARNESS-4): write benchmark/e2/spec/reader-docs.md, the documentation strings of every reader
the E2 harness can call, extracted verbatim from the library (as E1's benchmark/e1/spec/reader-docs.md).

    uv run python -m evaluation.e2.reader_docs [--check]

This is a **supplement**, not the E2 reader contracts: under E2-D3 the contracts are written from the design documents
and approved by the owner before any question is authored, and documentation strings are only a supplement to them
(design 5.2). --check exits 1 if the file is out of date.
"""

import argparse
import inspect
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from worldmodel import WorldModel, laboratory as lab, organisation as org  # noqa: E402

from evaluation.e2.readers import READERS  # noqa: E402

OUT = ROOT / "benchmark" / "e2" / "spec" / "reader-docs.md"
FUNCTIONS = {"measurement_calibration": lab.measurement_calibration, "calibration_status": lab.calibration_status,
             "office_holders": org.office_holders}


def target(name):
    return FUNCTIONS.get(name) or getattr(WorldModel, name)


def render():
    lines = ["# Documented semantics of the readers the Stage E2 harness can call", "",
             "Generated by `evaluation/e2/reader_docs.py` from the library's documentation strings (GAP-HARNESS-4, "
             "LABS-1.061). These are the readers' own descriptions of themselves: **not the E2 reader contracts**, which "
             "are written from the design documents and approved before any E2 question is authored (E2-D3); here "
             "they are only a supplement. Not implementation code and not system output.", "",
             "The harness's reader templates (parameters, cited evidence, presented derivations) are in "
             "`evaluation/e2/readers.py`.", ""]
    for name in sorted(READERS):
        fn = target(name)
        owner = "WorldModel." if name not in FUNCTIONS else f"{fn.__module__.rsplit('.', 1)[-1]}."
        sig = str(inspect.signature(fn)).replace("(self, ", "(")
        sig = sig.replace("(wm, ", "(wm, ")
        doc = inspect.cleandoc(fn.__doc__ or "(no documentation string)")
        lines += [f"## `{owner}{name}{sig}`", "", "```text", doc, "```", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        ok = OUT.exists() and OUT.read_text() == text
        print("up to date" if ok else f"{OUT} is out of date: run python -m evaluation.e2.reader_docs")
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    commit = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"], capture_output=True,
                            text=True).stdout.strip()
    print(f"wrote {OUT.relative_to(ROOT)} ({len(READERS)} readers, library at {commit})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
